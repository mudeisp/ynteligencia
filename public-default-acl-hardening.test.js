function psql(sql,database=db) {
 const env={...Object.fromEntries(Object.entries(process.env).filter(([k])=>!/^PG/i.test(k)||k==="PGPASSWORD")),PGCLIENTENCODING:"UTF8"};
 return execFileSync(bin,["-X","-w","-h",host,"-p",port,"-U","postgres","-d",database,
  "-v","ON_ERROR_STOP=1","-qAt","-f","-"],{input:sql,encoding:"utf8",env,
  maxBuffer:20*1024*1024,stdio:["pipe","pipe","pipe"]}).trim();
}
function file(name){return psql(fs.readFileSync(path.join(__dirname,name),"utf8"));}
function defaultSnapshot(where="true"){
 return psql(`select coalesce(jsonb_agg(jsonb_build_array(defaclrole,defaclnamespace,defaclobjtype,defaclacl::text) order by defaclrole,defaclnamespace,defaclobjtype),'[]') from pg_default_acl where ${where}`);
}
function objectSnapshot(){
 return psql(`select jsonb_build_object(
 'schemas',(select jsonb_agg(to_jsonb(n) order by n.oid) from pg_namespace n where n.nspname in ('public','acl_other')),
 'relations',(select jsonb_agg(jsonb_build_array(c.oid,n.nspname,c.relname,c.relkind,c.relacl::text,c.relrowsecurity,c.relforcerowsecurity) order by c.oid) from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname in ('public','acl_other') and c.relname not like 'future_%'),
 'columns',(select jsonb_agg(to_jsonb(c) order by table_schema,table_name,ordinal_position) from information_schema.columns c where table_schema in ('public','acl_other') and table_name not like 'future_%'),
 'policies',(select jsonb_agg(to_jsonb(p) order by schemaname,tablename,policyname) from pg_policies p where schemaname in ('public','acl_other')),
 'functions',(select jsonb_agg(jsonb_build_array(p.oid,pg_get_functiondef(p.oid),p.proacl::text,p.proconfig) order by p.oid) from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public'),
 'indexes',(select jsonb_agg(to_jsonb(i) order by indexname) from pg_indexes i where schemaname in ('public','acl_other') and tablename not like 'future_%'),
 'constraints',(select jsonb_agg(jsonb_build_array(conname,pg_get_constraintdef(oid)) order by oid) from pg_constraint where connamespace in ('public'::regnamespace,'acl_other'::regnamespace) and conrelid not in (select oid from pg_class where relname like 'future_%')),
 'rows_postgres',(select jsonb_agg(to_jsonb(t) order by id) from public.existing_postgres t),
 'rows_admin',(select jsonb_agg(to_jsonb(t) order by id) from public.existing_admin t))`);
}
function createFuture(creator,suffix){
 psql(`set role ${creator}; create table public.future_${suffix}(id bigint generated by default as identity primary key,note text); insert into public.future_${suffix}(note) values('fixture'); reset role`);
}
function assertSecure(table){
 const checks=JSON.parse(psql(`select jsonb_agg(jsonb_build_object('role',r.name,'privilege',p.name,'allowed',has_table_privilege(r.name,'public.${table}',p.name))) from unnest(array['anon','authenticated','service_role','acl_public_probe']) r(name) cross join unnest(array[${privs.map(p=>"'"+p+"'").join(",")}]) p(name)`));
 assert.equal(checks.length,32); for(const c of checks) assert.equal(c.allowed,false,JSON.stringify(c));
 assert.equal(psql(`select count(*) from pg_class c cross join lateral aclexplode(c.relacl) a where c.oid='public.${table}'::regclass and a.grantee=0`),"0");
 for(const role of [...apps,"acl_public_probe"]){
  assert.throws(()=>psql(`set role ${role}; truncate public.${table}`),e=>String(e.stderr).includes("permission denied"));
  assert.throws(()=>psql(`set role ${role}; select * from public.${table}`),e=>String(e.stderr).includes("permission denied"));
 }
}
